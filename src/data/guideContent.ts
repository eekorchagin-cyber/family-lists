export function flattenGuideSections(sections: GuideSection[] = GUIDE_SECTIONS): GuideSection[] {
  const out: GuideSection[] = []
  for (const section of sections) {
    out.push(section)
    if (section.children?.length) out.push(...flattenGuideSections(section.children))
  }
  return out
}

export function guideSectionsByIds(ids: string[]): GuideSection[] {
  const map = new Map(flattenGuideSections().map((section) => [section.id, section]))
  return ids.map((id) => map.get(id)).filter((section): section is GuideSection => Boolean(section))
}

export function guidePlainDocument(sections: GuideSection[] = GUIDE_SECTIONS): string {
  const lines: string[] = ['Как пользоваться', '', 'Содержание', '']
  let n = 1
  for (const section of sections) {
    lines.push(`${n}. ${section.title}`)
    section.children?.forEach((child, index) => {
      lines.push(`   ${n}.${index + 1}. ${child.title}`)
    })
    n += 1
  }
  lines.push('')

  const writeSection = (section: GuideSection, level: number) => {
    lines.push(section.title)
    lines.push('')
    for (const block of section.blocks) {
      if (block.type === 'p') {
        lines.push(block.text)
        lines.push('')
      } else if (block.type === 'ol') {
        block.items.forEach((item, index) => lines.push(`${index + 1}. ${item}`))
        lines.push('')
      } else {
        block.items.forEach((item) => lines.push(`• ${item}`))
        lines.push('')
      }
    }
    section.children?.forEach((child) => writeSection(child, level + 1))
  }

  sections.forEach((section) => writeSection(section, 1))
  return lines.join('\n').trim() + '\n'
}
